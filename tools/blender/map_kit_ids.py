"""Writes the map's mesh IDs (the kit and the buildings) into the tile builder (tools/tiles/lib/mapKitIds.ts).

    python3 tools/blender/map_kit_ids.py ids.txt

`ids.txt` holds "Name=rbxassetid://123" lines for an uploaded map_kit.fbx or map_buildings.fbx, and a
"Texture=rbxassetid://456" line for its palette (other lines are ignored). IDs already in the file are kept
unless replaced, so the kit and the buildings can be uploaded apart. Then `npm run tiles` puts the meshes in
the tiles; anything without an ID stays a blockout. Swatches are only ever added to the palette, so the
newest upload's palette colours every mesh: pass its Texture line.
"""

import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MANIFESTS = [os.path.join(REPO, "tools", "tiles", "lib", f) for f in ("mapKit.ts", "mapBuildings.ts")]
OUT = os.path.join(REPO, "tools", "tiles", "lib", "mapKitIds.ts")


def main():
	if len(sys.argv) != 2:
		raise SystemExit(__doc__)
	known = [n for path in MANIFESTS for n in re.findall(r"^\t(\w+): \{ size", open(path).read(), re.M)]
	# What's there already.
	current = open(OUT).read() if os.path.exists(OUT) else ""
	ids = dict(re.findall(r"^\t(\w+): \"(rbxassetid://\d+)\"", current, re.M))
	found = re.search(r'MAP_KIT_TEXTURE = "([^"]*)"', current)
	texture = found.group(1) if found else ""
	for line in open(sys.argv[1]):
		match = re.search(r"(\w+)=(rbxassetid://\d+)", line)
		if not match:
			continue
		name, asset = match.groups()
		if name == "Texture":
			texture = asset
		elif name in known:
			ids[name] = asset
		else:
			print(f"skipped {name}: not in the kit")
	lines = [
		"// GENERATED by tools/blender/map_kit_ids.py from the IDs Studio printed (tools/blender/README.md → The map",
		"// kit). Do not edit.",
		'import type { KitName } from "./kit.ts";',
		"",
		"/** The palette image the kit's meshes are coloured from. */",
		f"export const MAP_KIT_TEXTURE = {json.dumps(texture)};",
		"",
		"/** Each uploaded mesh's ID. A mesh that isn't here is built as its blockout. */",
	]
	if ids:
		lines.append("export const MAP_KIT_IDS: Partial<Record<KitName, string>> = {")
		lines += [f"\t{name}: {json.dumps(ids[name])}," for name in known if name in ids]
		lines.append("};")
	else:
		lines.append("export const MAP_KIT_IDS: Partial<Record<KitName, string>> = {};")
	with open(OUT, "w") as handle:
		handle.write("\n".join(lines) + "\n")
	missing = [n for n in known if n not in ids]
	print(f"{len(ids)} meshes with IDs; missing: {', '.join(missing) or 'none'}")
	print(f"palette: {texture or '(none: the meshes will be white)'}")


main()
