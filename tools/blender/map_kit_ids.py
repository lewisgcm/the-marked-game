"""Writes the map kit's mesh IDs into the tile builder (tools/tiles/lib/mapKitIds.ts).

    python3 tools/blender/map_kit_ids.py ids.txt

`ids.txt` holds what print_mesh_ids.lua printed after importing map_kit.fbx: "Name=rbxassetid://123" lines,
and a "Texture=rbxassetid://456" line for the palette (other lines are ignored). Then `npm run tiles` puts
the meshes in the tiles; anything without an ID stays a blockout.
"""

import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MANIFEST = os.path.join(REPO, "tools", "tiles", "lib", "mapKit.ts")
OUT = os.path.join(REPO, "tools", "tiles", "lib", "mapKitIds.ts")


def main():
	if len(sys.argv) != 2:
		raise SystemExit(__doc__)
	known = re.findall(r"^\t(\w+): \{ size", open(MANIFEST).read(), re.M)
	ids, texture = {}, ""
	for line in open(sys.argv[1]):
		match = re.search(r"(\w+)=(rbxassetid://\d+)", line)
		if not match:
			continue
		name, asset = match.groups()
		if name == "Texture":
			texture = asset
		elif name in known:
			ids[name] = asset
		else:
			print(f"skipped {name}: not in the kit")
	lines = [
		"// GENERATED by tools/blender/map_kit_ids.py from the IDs Studio printed (tools/blender/README.md → The map",
		"// kit). Do not edit.",
		'import type { KitName } from "./mapKit.ts";',
		"",
		"/** The palette image the kit's meshes are coloured from. */",
		f"export const MAP_KIT_TEXTURE = {json.dumps(texture)};",
		"",
		"/** Each uploaded mesh's ID. A mesh that isn't here is built as its blockout. */",
	]
	if ids:
		lines.append("export const MAP_KIT_IDS: Partial<Record<KitName, string>> = {")
		lines += [f"\t{name}: {json.dumps(ids[name])}," for name in known if name in ids]
		lines.append("};")
	else:
		lines.append("export const MAP_KIT_IDS: Partial<Record<KitName, string>> = {};")
	with open(OUT, "w") as handle:
		handle.write("\n".join(lines) + "\n")
	missing = [n for n in known if n not in ids]
	print(f"{len(ids)} meshes with IDs; missing: {', '.join(missing) or 'none'}")
	print(f"palette: {texture or '(none: the meshes will be white)'}")


main()
