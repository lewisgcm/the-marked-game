"""What the map's mesh kits (assets/map_kit.py, assets/map_buildings.py) share: measuring each mesh, and writing
the manifest the tile builder reads (tools/tiles/lib/*.ts): each mesh's size, and where its middle sits from
its base point, since Roblox centres a mesh on its bounding box.
"""

import os

import bpy
from mathutils import Vector

from . import mesh

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))


def measure(props):
	"""Builds every (name, builder) prop, bakes it, and returns [(object, (size, centre))] in Blender axes."""
	built = []
	for name, make in props:
		ob = make(name)
		ob.name = name
		mesh.select_only(ob)
		bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
		vs = [v.co for v in ob.data.vertices]
		lo = Vector((min(v.x for v in vs), min(v.y for v in vs), min(v.z for v in vs)))
		hi = Vector((max(v.x for v in vs), max(v.y for v in vs), max(v.z for v in vs)))
		built.append((ob, (tuple(hi - lo), tuple((lo + hi) / 2))))
	return built


def write_manifest(built, const, file, source):
	"""Writes `export const <const> = { Name: { size, centre } }` to tools/tiles/lib/<file>."""
	# Roblox axes: X = Blender X, Y = Blender Z (up), Z = Blender Y (Blender -Y front -> Roblox -Z). The
	# importer also turns X round (KIT_X_SIGN in tools/tiles/lib/kit.ts), as the old lobby kit found.
	f = lambda v: f"{v:.3f}".rstrip("0").rstrip(".")  # noqa: E731
	lines = [
		f"// GENERATED by tools/blender/assets/{source}.py (npm run models -- {source}). Do not edit.",
		'import type { KitMesh } from "./kit.ts";',
		"",
		f"export const {const} = {{",
	]
	for ob, (size, centre) in built:
		lines.append(
			f"\t{ob.name}: {{ size: [{f(size[0])}, {f(size[2])}, {f(size[1])}], "
			f"centre: [{f(centre[0])}, {f(centre[2])}, {f(centre[1])}] }},"
		)
	lines += ["} satisfies Record<string, KitMesh>;", ""]
	with open(os.path.join(REPO, "tools", "tiles", "lib", file), "w") as handle:
		handle.write("\n".join(lines))


def lay_out(built, row_width, gap):
	"""Lays the props out in rows for the preview (positions don't matter to the game)."""
	x, y, row_depth = 0.0, 0.0, 0.0
	for ob, (size, _) in built:
		if x + size[0] > row_width:
			x, y, row_depth = 0.0, y + row_depth + gap, 0.0
		lo_x = min(v.co.x for v in ob.data.vertices)
		lo_y = min(v.co.y for v in ob.data.vertices)
		ob.location = (x - lo_x, y - lo_y, 0)
		x += size[0] + gap
		row_depth = max(row_depth, size[1])
	return built[0][0]
