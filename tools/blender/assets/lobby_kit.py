"""The lobby kit: every low-poly lobby prop, plus the three ritual items, in one FBX.

Import it once with Studio's 3D Importer (Merge Meshes OFF, so each prop becomes its own
MeshPart named after it), then run tools/blender/print_mesh_ids.lua in the command bar and
paste the output back so the IDs can be written into assets/rojo/kit/*.model.json.

Every prop is modelled standing on z = 0 at its own origin, front facing -Y (Roblox -Z). Roblox
centres a mesh on its bounding box, so this build also writes src/shared/lobby/kitManifest.ts: each
prop's size and where its bounding-box centre sits relative to its base, which code uses to
stand props on the ground exactly.
"""

import json
import os

from mathutils import Vector

from lib import lowpoly, mesh, palette

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
PREVIEW_DIRECTION = (0.25, -1.0, 0.45)
PREVIEW_MARGIN = 0.75


def props():
	"""(name, builder) for every prop in the kit. Names become the MeshPart names in Roblox."""
	return [
		("Grave_Round", lambda n: lowpoly.gravestone(n, "round", seed=1)),
		("Grave_Gothic", lambda n: lowpoly.gravestone(n, "gothic", seed=2)),
		("Grave_Cross", lambda n: lowpoly.gravestone(n, "cross", seed=3)),
		("Grave_Broken", lambda n: lowpoly.gravestone(n, "broken", seed=4)),
		("Grave_Obelisk", lambda n: lowpoly.obelisk(n)),
		("Tree_A", lambda n: lowpoly.dead_tree(n, 11.0, seed=7)),
		("Tree_B", lambda n: lowpoly.dead_tree(n, 9.5, seed=12)),
		("LanternPost", lambda n: lowpoly.lantern_post(n)),
		("FenceSection", lambda n: lowpoly.fence_section(n)),
		("FencePillar", lambda n: lowpoly.fence_pillar(n)),
		("GatePillar", lambda n: lowpoly.gate_pillar(n)),
		("GateLeaf", lambda n: lowpoly.gate_leaf(n)),
		("GateArch", lambda n: lowpoly.gate_arch(n)),
		("ChapelFront", lambda n: lowpoly.chapel_front(n)),
		("BellTower", lambda n: lowpoly.bell_tower(n)),
		("Crypt", lambda n: lowpoly.crypt(n)),
		("Rock_A", lambda n: lowpoly.rock(n, (1.8, 1.4, 1.0), seed=11)),
		("Rock_B", lambda n: lowpoly.rock(n, (1.1, 1.0, 0.8), seed=14)),
		("Pedestal", lambda n: lowpoly.pedestal(n)),
		("RitualCandle", lambda n: lowpoly.ritual_candle(n)),
		# The ritual items keep the exact heights the game code expects (shared/lobby/ritualItems.ts).
		("Skull", lambda n: lowpoly.fit_height(lowpoly.skull(n, 1.0), 1.1)),
		("Book", lambda n: lowpoly.book(n)),
		("Candles", lambda n: lowpoly.candle_cluster(n)),
	]


def _bounds(ob):
	xs = [v.co.x for v in ob.data.vertices]
	ys = [v.co.y for v in ob.data.vertices]
	zs = [v.co.z for v in ob.data.vertices]
	return Vector((min(xs), min(ys), min(zs))), Vector((max(xs), max(ys), max(zs)))


def _write_manifest(entries):
	# Roblox axes: X = Blender X, Y = Blender Z (up), Z = Blender Y (Blender -Y front -> Roblox -Z).
	# (X may come in mirrored by the importer; KIT_X_SIGN in the TS file covers that.)
	lines = [
		"// GENERATED by tools/blender/assets/lobby_kit.py (npm run models -- lobby_kit). Do not edit.",
		"",
		"/** A kit prop: its bounding-box size, and its bounding-box centre relative to the prop's base point. */",
		"export interface KitProp {",
		"\tsize: Vector3;",
		"\tcentre: Vector3;",
		"}",
		"",
		"export type KitPropName =",
	]
	lines += [f'\t| "{name}"' for name in entries] 
	lines[-1] += ";"
	lines += ["", "export const KIT_PROPS: Record<KitPropName, KitProp> = {"]
	for name, (size, centre) in entries.items():
		lines.append(
			f"\t{name}: {{ size: new Vector3({size[0]:.3f}, {size[2]:.3f}, {size[1]:.3f}), "
			f"centre: new Vector3({centre[0]:.3f}, {centre[2]:.3f}, {centre[1]:.3f}) }},"
		)
	lines += ["};", ""]
	path = os.path.join(REPO, "src", "shared", "lobby", "kitManifest.ts")
	with open(path, "w") as handle:
		handle.write("\n".join(lines))
	with open(os.path.join(REPO, "assets", "models", "lobby_kit", "manifest.json"), "w") as handle:
		json.dump({n: {"size": list(s), "centre": list(c)} for n, (s, c) in entries.items()}, handle, indent="\t")


def build():
	palette.save_png(os.path.join(REPO, "assets", "models", "_palette", "palette.png"))
	os.makedirs(os.path.join(REPO, "assets", "models", "lobby_kit"), exist_ok=True)

	entries = {}
	built = []
	for name, make in props():
		ob = make(name)
		mesh.select_only(ob)
		import bpy

		bpy.ops.object.transform_apply(location=True, rotation=True, scale=True)
		lo, hi = _bounds(ob)
		entries[name] = (tuple(hi - lo), tuple((lo + hi) / 2))
		built.append((ob, hi - lo))
	_write_manifest(entries)

	# Lay the kit out in rows for the preview (positions don't matter to the game).
	x, y, row_depth = 0.0, 0.0, 0.0
	row_width = 60.0
	for ob, size in built:
		if x + size.x > row_width:
			x, y, row_depth = 0.0, y + row_depth + 3.0, 0.0
		ob.location = (x + size.x / 2, y + size.y / 2, 0)
		x += size.x + 2.0
		row_depth = max(row_depth, size.y)
